const { chromium } = require("playwright");
const fs = require("node:fs");
const path = require("node:path");

(async () => {
  const project = path.resolve(__dirname, "..");
  const port = process.env.PORT || "4177";
  const chapter = process.env.CHAPTER || "11";
  const recordDir = path.join(project, "qa", "recording");
  const output = path.join(project, "qa", `chapter${chapter}-screen.webm`);
  fs.mkdirSync(recordDir, { recursive: true });
  const browser = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
  const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, recordVideo: { dir: recordDir, size: { width: 1920, height: 1080 } } });
  await context.addInitScript(() => localStorage.clear());
  const createdAt = Date.now();
  const page = await context.newPage();
  await page.goto(`http://127.0.0.1:${port}/?auto=1&capture=1`, { waitUntil: "domcontentloaded", timeout: 60000 });
  await page.waitForSelector(".scene-safe", { timeout: 60000 });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1200);
  const startedAt = Date.now();
  await page.keyboard.press("Space");
  await page.waitForSelector(".final-scene", { timeout: 600000 });
  const finalSceneAt = Date.now();
  await page.waitForTimeout(6000);
  await page.screenshot({ path: path.join(project, "qa", "recording-final-frame.png") });
  const video = page.video();
  await page.close();
  if (!video) throw new Error("No Playwright recording was created");
  await video.saveAs(output);
  await context.close();
  await browser.close();
  fs.writeFileSync(path.join(project, "qa", "recording-metadata.json"), JSON.stringify({ chapter, createdAt, startedAt, finalSceneAt, preRollSeconds: (startedAt-createdAt)/1000, contentBeforeFinalSeconds: (finalSceneAt-startedAt)/1000, finalHoldSeconds: 6, sourceVideo: output }, null, 2));
})().catch((error) => { console.error(error); process.exit(1); });
