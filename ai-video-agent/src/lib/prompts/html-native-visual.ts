/** Final-render rules. These are intentionally not sent to the outline model. */
export const HTML_RENDER_QUALITY_GUIDANCE = `
## HTML 稳定美观渲染协议（强制）

### 1. 先选一种构图，不得混搭
- hook：超大标题或单一符号占据主视觉区，辅助信息退后。
- compare：左右或上下两区共用同一基线，只突出一个关键差异。
- process：3-5 个节点沿单一路径推进，不分叉、不回环。
- hierarchy：一个根节点连接 2-4 个子节点，层级最多两层。
- metric：一个大数字或一组可比长度为主角，刻度和说明降级。
- timeline：一条时间轴、2-5 个事件点，年份与事件严格对齐。
- quote：一句短引文作为主角，署名和来源明显更小。
- cause：2-4 个节点从原因单向传到结果，只保留一条因果链。
- spatial：以一个中心对象和周边关系建立空间，不做自由散点拼贴。
- summary：把前置信息收束到一个结论，不重新堆叠所有细节。

### 2. 严格使用输入的设计系统
- 当 SceneSpec.assetStrategy="chart" 时，不要手写柱高、折线路径、扇形路径、坐标刻度或气泡半径。在 visual-content 内输出一个 \`<script type="application/json" data-chart-spec>\`，正文必须是合法 JSON，字段为 \`type\`、\`data\`、可选的 \`unit/min/max/showLegend/showValues\`；每个 data 项至少包含 \`label\` 与数值 \`value\`，散点图另含数值 \`x/y\`。应用会用同一份数据确定性计算图形、标签和图例。屏幕主标题仍放在 text-zone。
- 当画面提示词或 SceneSpec 明确要求“饼状图/饼图”时，必须使用标准的**实心分块饼图**：所有数据类别都应是从圆心展开、完整覆盖 360° 的独立扇形，扇形之间保留清晰但极窄的浅色间隔；每块直接标出数值或百分比，并在旁边给出对应图例。扇形角度必须严格等于数值 × 3.6°（例如 78% = 280.8°、22% = 79.2°）；间隔只可略微缩小每块边缘，不能改变视觉比例。优先使用 SVG path 精确计算扇形，或等价的精确实现。禁止把它画成半圆仪表盘、环形图、甜甜圈图、单色圆环、进度环或只有中心百分比的圆环。若只有一个比例，至少画出该比例与“其余”两块扇形，不能用圆环替代。
- 把 themeTokens 映射为 :root CSS 变量后统一复用；已有 Token 时不得另造颜色、字体、圆角、阴影或动效时长。
- 主背景只用 background；主体文字只用 foreground；弱信息用 muted；accent 只强调唯一焦点；surface 仅在确有分区需要时使用。
- 全镜最多一个强调色、两种字重、三档字号、两种线宽和一种圆角。不要用渐变补救空白。
- 留白必须主动参与构图。视觉区未填满不是问题，不得添加无语义圆点、网格、光斑或装饰线来填空。

### 3. 固定复杂度预算
- 先根据内容容量选一个受保护的根布局：标题较短且视觉为主时用 data-layout="split"；标题较长或需水平全宽视觉时用 data-layout="stack"。不得同时使用两种布局。
- text-zone 与 visual-zone 内的元素只能使用各自的局部坐标；连线、标注、伪元素和位移动画也不得越界。区域之间的留白是不可占用的隔离带。
- visual-zone 内必须只有一个 data-role="visual-content" 总容器，所有主视觉、连线、标注和 composite 都放在其中。visual-content 固定占满区域且不做动画，动效只施加到它的后代元素。
- process / timeline / hierarchy / cause 画面必须把语义节点放进一个 Grid 或 Flex 容器，以显式 columns/rows/gap 排列；节点本身不得使用 position:fixed，绝对定位仅允许用于同一 visual-content 内不参与排版的连接线覆盖层。
- 设计时先保证完整构图留在 visual-content 内；不得依赖程序自动缩放、平移或裁切来掩盖越界。内容过多时删除次要元素或改用更合适的布局。
- 允许“有语义的组合遮挡”：多个部件确实需要叠合成同一个事物时（例如屏幕 + 边框 + 底座组成显示器），必须放入同一个 data-role="composite" 容器，可在容器内分层叠放。
- composite 仅用于低复杂度对象，并遵守“最多 8 个基础部件、2 类基础形状、1 层局部叠放”的预算；超过预算时不得硬拼，改用简化示意、图表、模拟 UI 或可验证的真实素材。
- composite 只能遮挡自己的非文字部件，不得压住可读文字、无关标签或其他语义对象，也不得越过 visual-zone 边界。除此之外的元素交叉都视为意外遮挡。
- 1280×720 画布底部 120px 为字幕安全区；生成的标题、标签、图形和动画终态都必须在 y=600 之上结束。
- DOM 元素尽量不超过 30 个；可见文字不超过 5 组，除标题外的独立短标签最多 2 个；SVG 图元不超过 20 个；禁止内嵌超长 path 数据。
- 只选择一种主要布局技术（Grid 或 Flex）；绝对定位仅用于画布内少量精准标注，不用于排列全部内容。
- 标题控制在两行以内；优先使用一条完整说明替代多个短标签。确需标签时不换行；所有文字必须完整显示，不使用省略号，不通过缩小字体解决溢出。
- 视觉主角占 visual-zone 的 45%-75%，辅助元素之间保持至少 16px 间距；任何元素不得越过安全区或覆盖 text-zone。

### 4. 动效服务信息
- 全镜只设计 2-3 个时间阶段：建立主角 → 揭示关系 → 停留结论。每阶段只改变一组相关元素。
- 优先 opacity、transform、scaleX/scaleY；最多定义 3 个 keyframes。避免同时改变位置、尺寸、旋转、模糊和颜色。
- 定位和动画必须分工：用外层容器负责居中或固定位置，用内层元素负责 transform 动画。禁止在同一个元素上同时使用 left/top:50% + translate(-50%,-50%) 居中和会改写 transform 的 keyframes；若必须共用元素，改用独立的 CSS translate 属性保存居中位移。
- 动画在总时长前 20% 完成建立、70% 前完成揭示，最后至少 25% 保持稳定终帧。
- 不循环、不闪烁、不弹跳、不持续旋转；prefers-reduced-motion 下直接显示清晰终态。

### 5. 输出前静默自检
在输出 HTML 前自行检查，但不要输出检查过程：
1. 缩略图观看时，是否能立刻识别唯一主角和主要关系？
2. 所有文字是否在 1280x720 安全区内完整可读且互不遮挡？
   text-zone 和 visual-zone 的连线、标签、边框及伪元素是否也完全留在各自区域内？
   所有有意叠放是否都位于同一 composite 内，并且确实组成一个事物，而非用 z-index 掩盖意外冲突？
   visual-content 内全部可见元素的外接边界是否完整落在 visual-zone 内，没有只露出一部分的对象？
3. 最终静止帧是否比动画过程更完整，而不是元素仍隐藏或停在半路？
4. 是否精确使用了输入 Token，且没有多余颜色、装饰、卡片或无语义图形？
5. 是否把可以由图形关系表达的内容又重复写成了短词？若是，删除短词。
6. 删除任一辅助元素或文字后若不影响理解，就删除它再输出。
`;

export function buildHtmlRenderQualityGuidance(canvasPreset?: CanvasPresetId): string {
  const canvas = getCanvasPreset(canvasPreset);
  const sharedGuidance = HTML_RENDER_QUALITY_GUIDANCE
    .replace(
      '- 1280×720 画布底部 120px 为字幕安全区；生成的标题、标签、图形和动画终态都必须在 y=600 之上结束。',
      `- ${canvas.design.width}×${canvas.design.height} 画布的字幕安全区为 y=${canvas.subtitleArea.top}–${canvas.subtitleArea.bottom}；生成的标题、标签、图形和动画终态都必须在 y=${canvas.contentArea.bottom} 之上结束。`,
    )
    .replace(
      '2. 所有文字是否在 1280x720 安全区内完整可读且互不遮挡？',
      `2. 所有文字是否在 ${canvas.design.width}x${canvas.design.height} 安全区内完整可读且互不遮挡？`,
    );
  return `${sharedGuidance}${buildPortraitVisualGuidance(canvasPreset)}`;
}
